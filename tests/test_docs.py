"""A derived number in a doc must equal the code it describes.

The skill's pitfall: "numbers typed into prose drift on the first edit". Three docs
restated the test count, LOC and scenario count and disagreed within two revisions.
`docs/sync_numbers.py` rewrites them; this test fails when someone forgets to run it.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from docs.sync_numbers import collect  # noqa: E402


@pytest.fixture(scope="module")
def numbers():
    return collect()


def test_the_code_counts_are_self_consistent(numbers):
    assert numbers["scenarios"] == 37
    assert numbers["invariants"] == 11
    assert numbers["states"] == 10
    assert numbers["tokens"] == 13


def test_design_note_states_the_real_scenario_and_invariant_count(numbers):
    text = (ROOT / "docs" / "DESIGN_NOTE.md").read_text()
    assert f"| Scenarios | {numbers['scenarios']} " in text
    assert f"| Invariants | {numbers['invariants']} " in text
    assert f"| States | {numbers['states']} |" in text
    assert f"| Terminal tokens | {numbers['tokens']} |" in text


def test_design_note_loc_matches_the_tree(numbers):
    text = (ROOT / "docs" / "DESIGN_NOTE.md").read_text()
    assert f"{numbers['src_loc']:,} / {numbers['test_loc']:,}" in text


def test_demo_states_the_real_test_count(numbers):
    text = (ROOT / "docs" / "DEMO.md").read_text()
    assert f"# {numbers['tests']} passed" in text


def test_the_design_note_is_about_one_page():
    """The brief asks for a condensed note; a 400-line spec is a different artifact."""
    words = len((ROOT / "docs" / "DESIGN_NOTE.md").read_text().split())
    assert words <= 1100, f"{words} words is more than a page"


def test_the_eval_table_is_generated_not_hand_written():
    """A hand-written table passes in the doc while the code regresses."""
    assert (ROOT / "EVAL_TABLE.md").exists()
    text = (ROOT / "EVAL_TABLE.md").read_text()
    assert "Generated by `python -m evals.harness`" in text
    assert "| # | Scenario | Expected | Got | Tools | Result |" in text


def test_every_scenario_appears_in_the_generated_table(numbers):
    text = (ROOT / "EVAL_TABLE.md").read_text()
    rows = re.findall(r"^\| (\d+) \|", text, re.M)
    assert sorted(int(r) for r in rows) == list(range(1, numbers["scenarios"] + 1))


def test_the_trace_excerpt_matches_the_trace_it_quotes():
    trace = ROOT / "traces" / "scenario_09.jsonl"
    doc = ROOT / "docs" / "TRACE_EXCERPT.md"
    assert trace.exists() and doc.exists()
    events = [line for line in trace.read_text().splitlines() if line.strip()]
    text = doc.read_text()
    assert f"**{len(events)} events**" in text
    # the terminal line quoted in the doc must be the real terminal event
    assert '"outcome": "booked_verified_after_timeout"' in text


def test_the_bug_log_documents_every_fixed_defect():
    text = (ROOT / "docs" / "BUGS.md").read_text()
    bugs = re.findall(r"^## Bug (\d+)", text, re.M)
    assert len(bugs) >= 6, f"only {len(bugs)} bugs recorded"
    assert bugs == [str(i) for i in range(1, len(bugs) + 1)], "bug numbers not contiguous"
