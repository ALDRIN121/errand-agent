"""Generate docs/TRACE_EXCERPT.md from a real trace.

Writing the excerpt by hand is how a document drifts from the run it claims to
describe. `sequence` and `terminal` below are dated facts, so this script exists to
produce the dated result on demand: `python -m docs.render_trace_excerpt`.

`sequence` below is dated, and the claim in DESIGN_NOTE is about the FSM, not about
this particular run; if they ever disagree the run wins and the note is wrong.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRACE = ROOT / "traces" / "scenario_09.jsonl"
OUT = ROOT / "docs" / "TRACE_EXCERPT.md"

# What each event proves. Kept next to the renderer so an event with no stated
# purpose is visible as a gap rather than passing unremarked.
ANNOTATIONS = {
    "turn": "a user turn enters the loop; the state is recorded with it",
    "context": "the budget manifest: real token count, how many memories were "
               "included and excluded",
    "action": "the model's structured proposal — this is the model choosing, not prose",
    "action_attributed": "I8: the call below is tied to the action above by hash",
    "tool_call": "the dispatch, after gateway legality and argument validation",
    "status_query": "an authoritative status check, which is how a timeout resolves",
    "approval_requested": "the frozen digest and the exact text the user saw",
    "side_effect_error": "the timeout — from here the run may or may not have booked",
    "side_effect_retry": "a transient retry on the same idempotency key",
    "side_effect_ok": "a confirmed effect, with the booking it produced",
    "terminal": "the outcome token, which one renderer turns into the final sentence",
    "proactive_delivered": "an unattended message, from the rules-only path",
    "event_received": "a system event with no user turn behind it",
    "recovery_offered": "the proactive offer, before any approval exists",
    "outbox_queued": "one row queued for delivery",
    "clock_advanced": "test clock movement, for TTL scenarios",
    "tool_refused": "the gateway refusing an illegal or malformed call",
    "tool_error": "a normalised tool failure",
    "tool_retry": "a transient retry",
}


def render(path: Path = TRACE) -> str:
    if not path.exists():
        raise SystemExit(f"{path} missing: run `python -m evals.harness --watcher`")
    events = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]

    lines = [
        "# Trace excerpt",
        "",
        "Generated by `python -m docs.render_trace_excerpt` from",
        f"`traces/{path.name}` — **{len(events)} events**, one run.",
        "",
        "Scenario 9, *timeout-that-booked*: the one the brief cares about most. The",
        "`book` call times out, so the run must not claim either outcome. It asks the",
        "authoritative status tool, which says the booking exists.",
        "",
        "```jsonl",
    ]
    for e in events:
        lines.append(json.dumps(e, default=str)[:200])
    lines += ["```", "", "## What each event proves", ""]

    seen = []
    for e in events:
        kind = e["type"]
        if kind not in seen:
            seen.append(kind)

    lines += ["| # | Event | Proves |", "|---|---|---|"]
    for kind in seen:
        lines.append(f"| {events.index(next(e for e in events if e['type'] == kind)) + 1} "
                     f"| `{kind}` | {ANNOTATIONS.get(kind, '**undocumented event**')} |")

    lines += [
        "",
        "## What this run proves",
        "",
        "1. **A timeout is not an outcome.** Event 9 records the failure; event 11",
        "   records the booking. The success claim comes only from the status query.",
        "2. **The retry is not blind.** Event 10 queries by idempotency key, so it can",
        "   tell 'booked' from 'not booked' without re-booking.",
        "3. **Attribution is on the record.** Events 4 and 8 tie the two dispatches to",
        "   the model actions that proposed them, which is what separates a driven run",
        "   from a scripted one.",
        "4. **The budget was real.** Event 2 carries an actual token count (806), not a",
        "   redaction, because the manifest exists to make that auditable.",
        "",
        "Regenerate with `python -m evals.harness --watcher` then",
        "`python -m docs.render_trace_excerpt`.",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render())
    print(OUT.read_text())
